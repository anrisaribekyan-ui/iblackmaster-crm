export function buildGuide(source: Source, dest: Dest, categories: string[]): Guide {
  const sections: GuideSection[] = []
  const chosen = categories.length ? categories : ['full']
  for (const c of CATEGORIES) {
    if (!chosen.includes(c.id)) continue
    if (c.id === 'full') sections.push({ title: c.title, steps: full(source, dest) })
    else sections.push({ title: c.title, steps: PER_CATEGORY[c.id](source, dest) })
  }
  const before = [
    'Зарядите оба телефона хотя бы до 50% (лучше поставить на зарядку на время переноса).',
    'Узнайте у клиента и выпишите: Apple ID / аккаунт Google, их пароли, номер телефона для кодов, код‑пароль от экрана. Без них вход на новом телефоне не получится.',
    'Проверьте свободное место: на приёмнике, на флешке или в облаке должно хватать места под всё, что переносите.',
    source === 'iphone'
      ? 'Обновите iOS до последней доступной версии, если это возможно. «Найти iPhone» копированию не мешает: его отключают только перед сбросом телефона.'
      : 'На Android войдите в Настройки → Google и убедитесь, что аккаунт синхронизируется; проверьте, что режим «Не беспокоить» не блокирует коды.',
    'Подготовьте кабели и переходники: Lightning / USB‑C, OTG‑адаптер, кабель для компьютера, флешка нужного разъёма.',
  ]
  const after = [
    'Откройте на новом месте несколько контактов, фото, чат — клиент должен лично увидеть, что всё на месте.',
    'Не стирайте и не сбрасывайте старый телефон, пока клиент не подтвердил, что данные перенесены. Лучше хранить его хотя бы несколько дней.',
    'Если использовали флешку или компьютер, удалите с чужих устройств временные копии, где лежат пароли и личные данные.',
    'Отметьте в заказе, что перенесено и на что (флешка, облако, телефон), и кто проверял.',
  ]
  const warnings = [
    'Перенос выполняется только с согласия владельца телефона и в его присутствии или по его письменному разрешению. Чужие аккаунты и пароли без разрешения не используем.',
  ]
  if (source === 'iphone' && dest === 'android') warnings.push('Полную копию iPhone на Android перенести нельзя: приложения, часть настроек и SMS не переедут.')
  if (source === 'android' && dest === 'iphone') warnings.push('Приложения Android на iPhone не работают: их ставят заново из App Store.')
  if (dest === 'flash' || dest === 'pc') warnings.push('Копия на флешке или компьютере не зашифрована, если вы не включили шифрование. Передайте её клиенту и не оставляйте у себя.')
  return { before, sections, after, warnings }
}
