def add_missing(db: Session) -> int:
    from app.models import Employee, Order

    if db.scalars(select(Employee).where(Employee.is_owner.is_(True))).first() is None:
        return 0  # пустая база (свежая установка, тесты) — переносить нечего
    importer = Importer(db)
    added = 0
    for source in ROWS:
        if source["Номер заказа"] in importer.orders:
            continue
        row = {"Статус": "Принят", "Локация": LOCATION, "Тип заказа": "Негарантийный", "Внешний вид": "царапины, потертости",
               "Менеджер": source["Мастер"], "Менеджер создавший заказ": source["Мастер"], "Срочно": "Нет",
               "Сумма заказа": 0, "Оплачено по заказу": 0, **source}
        importer.import_row(row)
        order = importer.orders[source["Номер заказа"]]
        order.appearance = ["царапины", "потертости"]
        order.problems = [source["Неисправность"]] if source["Неисправность"] else []
        added += 1
    db.flush()
    if added:
        importer.finish()
        db.flush()
    return added


def main() -> int:
    from app.db import SessionLocal

    db = SessionLocal()
    try:
        added = add_missing(db)
        if "--commit" in sys.argv:
            db.commit()
            print(f"Добавлено заказов: {added}. Записано.")
        else:
            db.rollback()
            print(f"Пробный прогон: добавилось бы заказов: {added}. Для записи --commit.")
    finally:
        db.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
